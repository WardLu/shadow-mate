const poemEntries = POEMS.flatMap((poem, poemIndex) => {
  const ids = poemSpeechIds(poemIndex);
  return [
    { contentId: ids.header, locale: "zh-CN", text: `古诗《${poem.t}》，${poem.a}` },
    ...poem.c.map((line, lineIndex) => ({
      contentId: ids.line(lineIndex),
      locale: "zh-CN",
      text: line.replace(/[，。！？、；：]/g, ""),
    })),
  ];
});

